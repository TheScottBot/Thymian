package fyi.punkdev.thymian.icons

import com.android.ide.common.vectordrawable.Svg2Vector
import fyi.punkdev.thymian.domain.weather.WeatherCondition
import java.io.ByteArrayOutputStream
import java.io.File
import java.nio.file.Files

/** Where the conversion reads and writes, relative to the repository. */
data class IconConversionPaths(
    val svgDirectory: File,
    val drawableDirectory: File,
    val lookupFile: File,
) {
    companion object {
        fun inRepository(repositoryRoot: File) =
            IconConversionPaths(
                svgDirectory = File(repositoryRoot, "third_party/meteocons/monochrome"),
                drawableDirectory = File(repositoryRoot, "app/src/main/res/drawable"),
                lookupFile = File(repositoryRoot, "app/src/main/kotlin/fyi/punkdev/thymian/widget/WeatherIconDrawables.kt"),
            )
    }
}

object IconNaming {
    fun resourceNameFor(iconName: String): String = "weather_" + iconName.replace('-', '_')
}

/**
 * Converts the vendored Meteocons SVGs named by WeatherCondition into Android
 * vector drawables with Android's own converter (CWD24), and writes the lookup
 * from icon name to drawable. The vendored files are never edited; two exact
 * equivalences are applied on the way in. `currentColor` becomes white, so the
 * widget can tint each icon to the text colour. And an alpha mask
 * (`mask-type:alpha`) whose shapes are all opaque black is a plain clip: the
 * converter only accepts a mask whose own element is filled solid white (Android
 * tools sdk-common, SvgClipPathNode.validate), so such a mask is rewritten as a
 * white luminance mask, which draws identically. A mask with any other colour or
 * any opacity is left as it is, and the converter then refuses it. Any warning
 * from the converter stops the run, because a quietly dropped mask or shape would
 * change an icon.
 */
object WeatherIconConversion {
    private const val WHITE = "#FFFFFF"

    private val alphaMaskPattern = Regex("<mask\\b[^>]*mask-type:alpha[^>]*>.*?</mask>", RegexOption.DOT_MATCHES_ALL)
    private val fillPattern = Regex("fill=\"([^\"]*)\"")
    private val opaqueBlack = setOf("#000", "#000000")

    /** Applies the two equivalences described above; the result draws exactly as the original. */
    fun prepareForConversion(svgText: String): String =
        alphaMaskPattern
            .replace(svgText) { alphaMask -> asWhiteClipMaskIfOpaque(alphaMask.value) }
            .replace("currentColor", WHITE)

    private fun asWhiteClipMaskIfOpaque(alphaMask: String): String {
        val fills = fillPattern.findAll(alphaMask).map { fill -> fill.groupValues[1].uppercase() }.toList()
        val everyShapeOpaqueBlack = fills.isNotEmpty() && fills.all { fill -> fill in opaqueBlack } && !alphaMask.contains("opacity")
        if (!everyShapeOpaqueBlack) return alphaMask
        return fillPattern
            .replace(alphaMask, "fill=\"$WHITE\"")
            .replace(" style=\"mask-type:alpha\"", "")
            .replaceFirst("<mask ", "<mask fill=\"$WHITE\" ")
    }

    fun convert(paths: IconConversionPaths) {
        paths.drawableDirectory.mkdirs()
        val iconNames = WeatherCondition.allIconNames().sorted()
        for (iconName in iconNames) {
            val svgFile = File(paths.svgDirectory, "$iconName.svg")
            check(svgFile.isFile) { "vendored icon missing: ${svgFile.path}" }
            val vectorDrawable = convertOne(iconName, prepareForConversion(svgFile.readText()))
            File(paths.drawableDirectory, IconNaming.resourceNameFor(iconName) + ".xml").writeText(vectorDrawable)
        }
        paths.lookupFile.parentFile.mkdirs()
        paths.lookupFile.writeText(lookupSource(iconNames))
    }

    private fun convertOne(
        iconName: String,
        whiteSvg: String,
    ): String {
        val temporarySvg = Files.createTempFile("thymian-$iconName", ".svg")
        try {
            Files.writeString(temporarySvg, whiteSvg)
            val output = ByteArrayOutputStream()
            val conversionLog = Svg2Vector.parseSvgToXml(temporarySvg, output)
            check(conversionLog.isBlank()) { "$iconName did not convert cleanly: $conversionLog" }
            val header =
                "<!-- Generated by tools/icon-conversion from third_party/meteocons/monochrome/$iconName.svg (CWD24). " +
                    "Do not edit. -->\n"
            return header + output.toString(Charsets.UTF_8).trimEnd() + "\n"
        } finally {
            Files.deleteIfExists(temporarySvg)
        }
    }

    private fun lookupSource(iconNames: List<String>): String {
        val branches =
            iconNames.joinToString(
                separator = "\n",
            ) { iconName -> "            \"$iconName\" -> R.drawable.${IconNaming.resourceNameFor(iconName)}" }
        return """
            |// Generated by tools/icon-conversion from WeatherCondition (CWD24). Do not edit; regenerate with
            |// ./gradlew :icon-conversion:convertWeatherIcons
            |package fyi.punkdev.thymian.widget
            |
            |import fyi.punkdev.thymian.R
            |
            |/** The drawable for each Meteocons icon name that WeatherCondition uses. */
            |object WeatherIconDrawables {
            |    fun forIconName(iconName: String): Int =
            |        when (iconName) {
            |$branches
            |            else -> R.drawable.weather_not_available
            |        }
            |}
            |
            """.trimMargin()
    }
}

/** Argument: the repository root. */
fun main(arguments: Array<String>) {
    require(arguments.size == 1) { "usage: WeatherIconConversionKt repository_root" }
    WeatherIconConversion.convert(IconConversionPaths.inRepository(File(arguments[0])))
    println("weather icons converted: ${WeatherCondition.allIconNames().size}")
}
