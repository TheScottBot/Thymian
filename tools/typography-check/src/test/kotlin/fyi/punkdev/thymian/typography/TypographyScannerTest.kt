package fyi.punkdev.thymian.typography

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertThrows
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.io.File

/**
 * Every violating character is written as a Unicode escape so this file passes
 * the scan it tests. Each planted case proves a rule can fail (datum 0.4).
 */
class TypographyScannerTest {
    private val emDash = "\u2014"
    private val enDash = "\u2013"
    private val doubleHyphen = "-".repeat(2)
    private val tripleHyphen = "-".repeat(3)

    @Test
    fun `em dash is reported with line and column`() {
        val violations = TypographyScanner.scanText("notes.md", "first line\nsecond $emDash line\n")

        assertEquals(listOf(TypographyViolation("notes.md", 2, 8, TypographyRule.EM_DASH)), violations)
    }

    @Test
    fun `en dash is reported`() {
        val violations = TypographyScanner.scanText("Strings.kt", "val range = \"1${enDash}2\"")

        assertEquals(listOf(TypographyViolation("Strings.kt", 1, 15, TypographyRule.EN_DASH)), violations)
    }

    @Test
    fun `double hyphen in prose is reported`() {
        val violations = TypographyScanner.scanText("README.md", "It works $doubleHyphen mostly.")

        assertEquals(listOf(TypographyViolation("README.md", 1, 10, TypographyRule.HYPHEN_RUN)), violations)
    }

    @Test
    fun `triple hyphen between words is reported once`() {
        val violations = TypographyScanner.scanText("README.md", "before${tripleHyphen}after")

        assertEquals(listOf(TypographyViolation("README.md", 1, 7, TypographyRule.HYPHEN_RUN)), violations)
    }

    @Test
    fun `markdown table separator row is exempt`() {
        val tableText = "| Name | Value |\n|$tripleHyphen|:$tripleHyphen:|\n| a | b |\n"

        assertEquals(emptyList<TypographyViolation>(), TypographyScanner.scanText("table.md", tableText))
    }

    @Test
    fun `command line flag token is exempt`() {
        val commandText = "./gradlew ${doubleHyphen}no-daemon build and `adb ${doubleHyphen}version`"

        assertEquals(emptyList<TypographyViolation>(), TypographyScanner.scanText("README.md", commandText))
    }

    @Test
    fun `xml comment delimiters are exempt but a hyphen run inside the comment is not`() {
        val cleanComment = "<!$doubleHyphen Explains the layout. $doubleHyphen>"
        val dirtyComment = "<!$doubleHyphen Explains $doubleHyphen badly. $doubleHyphen>"

        assertEquals(emptyList<TypographyViolation>(), TypographyScanner.scanText("layout.xml", cleanComment))
        assertEquals(
            listOf(TypographyViolation("layout.xml", 1, 15, TypographyRule.HYPHEN_RUN)),
            TypographyScanner.scanText("layout.xml", dirtyComment),
        )
    }

    @Test
    fun `single hyphens and hyphenated words are fine`() {
        val text = "A well-known, self-documenting name: x - y, and a list item\n- like this"

        assertEquals(emptyList<TypographyViolation>(), TypographyScanner.scanText("prose.md", text))
    }

    @Test
    fun `violation describes itself as path line column and rule`() {
        val violation = TypographyViolation("docs/plan.md", 4, 2, TypographyRule.EM_DASH)

        assertEquals("docs/plan.md:4:2: em dash (U+2014)", violation.toString())
    }

    @Test
    fun `binary files are skipped and excluded paths are not read`(
        @TempDir repositoryRoot: File,
    ) {
        File(repositoryRoot, "image.png").writeBytes(byteArrayOf(0x50, 0x00, 0x2D, 0x2D, 0x41))
        File(repositoryRoot, "gradlew").writeText("exec java $doubleHyphen \"\$@\"\n")
        File(repositoryRoot, "notes.md").writeText("clean${emDash}not\n")

        val violations =
            TypographyScanner.scanFiles(
                repositoryRoot,
                relativePaths = listOf("image.png", "gradlew", "notes.md"),
                excludedPaths = setOf("gradlew"),
            )

        assertEquals(listOf(TypographyViolation("notes.md", 1, 6, TypographyRule.EM_DASH)), violations)
    }

    @Test
    fun `exclusion list reads explicit paths and ignores comments and blank lines`() {
        val listText = "# Generated by Gradle, kept verbatim.\ngradlew\n\ngradlew.bat\n"

        assertEquals(setOf("gradlew", "gradlew.bat"), ExcludedPathList.parse(listText))
    }

    @Test
    fun `exclusion list refuses a pattern because the datum requires explicit paths`() {
        val failure =
            assertThrows(IllegalArgumentException::class.java) {
                ExcludedPathList.parse("third_party/*\n")
            }

        assertEquals("excluded path must be explicit, not a pattern: third_party/*", failure.message)
    }

    @Test
    fun `an on device test name with a character dex cannot hold is reported`() {
        val source =
            "class Example {\n    @Test\n    fun `keeps the place, name`() = Unit\n" +
                "    fun `it's fine`() = Unit\n    fun `plain words only`() = Unit\n}\n"

        assertEquals(
            listOf(
                TypographyViolation("app/src/androidTest/kotlin/Example.kt", 3, 9, TypographyRule.DEX_UNSAFE_TEST_NAME),
                TypographyViolation("app/src/androidTest/kotlin/Example.kt", 4, 9, TypographyRule.DEX_UNSAFE_TEST_NAME),
            ),
            TypographyScanner.scanText("app/src/androidTest/kotlin/Example.kt", source),
        )
    }

    @Test
    fun `JVM test names may use commas because they never go through dex`() {
        val source = "    fun `parses a, b and c`() = Unit\n"

        assertEquals(emptyList<TypographyViolation>(), TypographyScanner.scanText("domain/src/test/kotlin/Example.kt", source))
    }
}
